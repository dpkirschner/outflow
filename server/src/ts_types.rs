//! Generates `app/src/types.ts`, the TS mirror of every DTO the API sends.
//!
//! `cargo test -p outflow-server --features ts` fails when the committed file
//! is stale; rerun with `UPDATE_TYPES=1` to rewrite it. The types derive
//! `ts_rs::TS` behind the `ts` feature, so default builds don't pull ts-rs in.
//!
//! To add a type: derive `TS` on it (`#[cfg_attr(feature = "ts",
//! derive(ts_rs::TS))]`) and list it in the section for its module below.
//! Order inside a section is the order in the file.

use std::path::PathBuf;

use ts_rs::{Config, TS};

const HEADER: &str = "\
// GENERATED by server/src/ts_types.rs from the Rust DTOs. Do not edit.
// Regenerate: UPDATE_TYPES=1 cargo test -p outflow-server --features ts types_ts
//
// serde sends struct fields as snake_case and enums as their variant names.
// Every money value is integer cents; outflows are negative. Times are epoch
// seconds unless a field says otherwise.
";

/// Appends `docs + export decl` for each listed type.
macro_rules! decls {
    ($cfg:expr, $out:expr, [$($t:ty),* $(,)?]) => {
        $(
            if let Some(docs) = <$t as TS>::docs() {
                $out.push_str(&docs);
            }
            $out.push_str("export ");
            $out.push_str(&pretty(&<$t as TS>::decl($cfg)));
            $out.push_str("\n\n");
        )*
    };
}

fn render() -> String {
    // i64 crosses the wire as a JSON number (epoch seconds, counts); JS
    // doubles hold them exactly at our magnitudes.
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(HEADER);
    out.push('\n');

    // --- core::model ---
    {
        use outflow_core::model::*;
        decls!(
            &cfg,
            out,
            [
                AccountKind,
                CategorySource,
                TxnFlag,
                Account,
                Transaction,
                Mark,
                PlaidItem,
                SyncEntry,
            ]
        );
    }

    // --- core::query, core::subscriptions ---
    {
        use outflow_core::query::*;
        use outflow_core::subscriptions::*;
        decls!(
            &cfg,
            out,
            [
                TxnPage,
                CategorySpend,
                MerchantSpend,
                MovedFlow,
                MovedLane,
                FlowMonth,
                Cadence,
                Subscription,
            ]
        );
    }

    // --- core::ledger ---
    {
        use outflow_core::ledger::*;
        use outflow_core::subscriptions::{RhythmEntry, StreamCadence, Trend};
        decls!(
            &cfg,
            out,
            [
                StreamCadence,
                Trend,
                RhythmEntry,
                Source,
                Stream,
                LineItem,
                TransferGroup,
                LedgerStats,
                Coverage,
                LedgerView
            ]
        );
    }

    // --- core::balances, core::activity ---
    {
        use outflow_core::activity::ActivityRow;
        use outflow_core::balances::*;
        decls!(
            &cfg,
            out,
            [
                Group,
                HoldingRow,
                AccountBalance,
                GroupBalance,
                Totals,
                BalancesView,
                DayTotals,
                PositionRow,
                PositionPoint,
                ActivityRow
            ]
        );
    }

    // --- core::perks ---
    {
        use outflow_core::perks::*;
        decls!(
            &cfg,
            out,
            [
                Reward,
                Cap,
                Offer,
                FindingKind,
                Finding,
                CardStatus,
                PerksReport
            ]
        );
    }

    // --- server ---

    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// ts-rs emits an object type on one line. Put each top-level field on its
/// own line (doc comment above it); nested objects stay inline. Anything that
/// isn't a plain `type X = { ... };` (unions, intersections) passes through.
fn pretty(decl: &str) -> String {
    let Some(open) = decl.find("= {") else {
        return decl.to_owned();
    };
    let (head, rest) = decl.split_at(open + 3);
    let Some(body) = rest.strip_suffix("};") else {
        return decl.to_owned();
    };

    let mut fields: Vec<String> = Vec::new();
    let mut cur = String::new();
    let (mut depth, mut in_doc, mut in_str) = (0i32, false, false);
    let chars: Vec<char> = body.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if in_doc {
            cur.push(c);
            if c == '/' && cur.ends_with("*/") {
                in_doc = false;
            }
        } else if in_str {
            cur.push(c);
            if c == '"' {
                in_str = false;
            }
        } else {
            match c {
                '/' if chars.get(i + 1) == Some(&'*') => {
                    in_doc = true;
                    cur.push(c);
                }
                '"' => {
                    in_str = true;
                    cur.push(c);
                }
                '{' | '[' | '(' => {
                    depth += 1;
                    cur.push(c);
                }
                '}' | ']' | ')' => {
                    depth -= 1;
                    if depth < 0 {
                        return decl.to_owned();
                    }
                    cur.push(c);
                }
                ',' if depth == 0 => fields.push(std::mem::take(&mut cur)),
                _ => cur.push(c),
            }
        }
        i += 1;
    }
    if depth != 0 || in_doc || in_str {
        return decl.to_owned();
    }
    fields.push(cur);

    let mut out = format!("{}\n", head.trim_end());
    for f in fields.iter().map(|f| f.trim()).filter(|f| !f.is_empty()) {
        for line in f.lines() {
            out.push_str("  ");
            out.push_str(line);
            out.push('\n');
        }
        out.truncate(out.len() - 1);
        out.push_str(",\n");
    }
    out.push_str("};");
    out
}

fn types_ts_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../app/src/types.ts")
}

#[test]
fn types_ts() {
    let want = render();
    let path = types_ts_path();
    if std::env::var_os("UPDATE_TYPES").is_some() {
        std::fs::write(&path, &want).expect("write app/src/types.ts");
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "app/src/types.ts is stale. Regenerate with:\n  \
         UPDATE_TYPES=1 cargo test -p outflow-server --features ts types_ts"
    );
}
